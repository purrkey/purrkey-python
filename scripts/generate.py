"""Regenerate src/purrkey/types.py from openapi/openapi.yaml.

    uv run python scripts/generate.py           regenerate from the vendored contract
    uv run python scripts/generate.py --fetch   download the live contract first
    uv run python scripts/generate.py --check   fail if types.py is out of date

Descriptions are dropped from the generated types: the API reference at
https://purrkey.app/docs is the documentation of record.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path
from typing import Any

import yaml

CONTRACT_URL = "https://purrkey.app/docs/openapi.yaml"
ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "openapi" / "openapi.yaml"
TYPES = ROOT / "src" / "purrkey" / "types.py"
ANNOTATIONS = {"description", "summary", "example"}
HEADER = "# Generated by scripts/generate.py from openapi/openapi.yaml. Do not edit.\n"


def strip(node: Any, is_properties: bool = False) -> Any:
    """Drop annotations; keys under `properties` are field names and stay."""
    if isinstance(node, list):
        return [strip(item) for item in node]
    if not isinstance(node, dict):
        return node
    return {
        key: strip(value, not is_properties and key == "properties")
        for key, value in node.items()
        if is_properties or key not in ANNOTATIONS
    }


def generate() -> str:
    contract = strip(yaml.safe_load(CONTRACT.read_text()))
    with tempfile.TemporaryDirectory() as work:
        source = Path(work) / "openapi.yaml"
        target = Path(work) / "types.py"
        source.write_text(yaml.safe_dump(contract, allow_unicode=True))
        subprocess.run(
            [
                "datamodel-codegen",
                "--input", str(source),
                "--input-file-type", "openapi",
                "--output", str(target),
                "--output-model-type", "typing.TypedDict",
                "--target-python-version", "3.10",
                "--disable-timestamp",
                "--enum-field-as-literal", "all",
            ],
            check=True,
        )
        return HEADER + target.read_text()


def main() -> None:
    if "--fetch" in sys.argv:
        with urllib.request.urlopen(CONTRACT_URL, timeout=30) as response:
            CONTRACT.write_bytes(response.read())
    output = generate()
    if "--check" in sys.argv:
        if TYPES.read_text() != output:
            sys.exit("src/purrkey/types.py is out of date. Run scripts/generate.py.")
        print("src/purrkey/types.py is up to date")
        return
    TYPES.write_text(output)
    print(f"Wrote {TYPES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
